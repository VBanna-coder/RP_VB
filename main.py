    def _fill_country_list(self, role):
        if not self.app.state.countries:
            lbl = Label(text="Нет стран.", size_hint_y=None, height=dp(50))
            lbl.color = (0.7, 0.7, 0.7, 1)
            self.cont.add_widget(lbl)
            return
        for c in self.app.state.countries:
            if role == "buyer" and self.seller and c.name == self.seller.name:
                continue
            text = "{} {}   👥{}  💰{}".format(c.emoji, c.name, c.population, c.coins)
            b = Button(text=text, size_hint_y=None, height=dp(48), font_size=dp(13))
            b.background_normal = ""
            b.background_color = (0.15, 0.20, 0.30, 1)
            b.color = (0.85, 0.95, 1.0, 1)
            if role == "seller":
                b.bind(on_release=lambda inst, cc=c: self._set_seller(cc))
            else:
                b.bind(on_release=lambda inst, cc=c: self._set_buyer(cc))
            self.cont.add_widget(b)

    def _fill_resource_list(self):
        for code, name, emoji in RESOURCES:
            have = self.seller.resources.get(code, 0)
            if have <= 0:
                continue
            val = RESOURCE_VALUE.get(code, 1)
            text = "{} {}  (у продавца: {})   ≈{}💰/ед.".format(emoji, name, have, val)
            b = Button(text=text, size_hint_y=None, height=dp(44), font_size=dp(12))
            b.background_normal = ""
            b.background_color = (0.10, 0.15, 0.10, 1)
            b.color = (0.85, 1.0, 0.85, 1)
            b.bind(on_release=lambda inst, cc=code: self._set_resource(cc))
            self.cont.add_widget(b)

    def _fill_setup_shortcut(self):
        b = Button(text="← Выбрать другой ресурс", size_hint_y=None, height=dp(36), font_size=dp(12))
        b.bind(on_release=lambda *a: self._back_to_resource())
        self.cont.add_widget(b)

    def _set_seller(self, c):
        self.seller = c
        self.mode = "buyer"
        self._rebuild()

    def _set_buyer(self, c):
        self.buyer = c
        self.mode = "resource"
        self._rebuild()

    def _set_resource(self, code):
        self.resource = code
        self.ti_price.text = str(RESOURCE_VALUE.get(code, 1))
        self.mode = "setup"
        self._rebuild()

    def _back_to_resource(self):
        self.mode = "resource"
        self._rebuild()

    def _parse_params(self):
        try:
            amount = int((self.ti_amount.text or "").strip())
        except Exception:
            amount = 0
        try:
            price = int((self.ti_price.text or "").strip())
        except Exception:
            price = 0
        if amount <= 0:
            self.status.text = "Количество должно быть > 0"
            return None
        if price < 0:
            self.status.text = "Цена не может быть отрицательной"
            return None
        return amount, price

    def _do_once(self, *a):
        try:
            p = self._parse_params()
            if not p:
                return
            amount, price = p
            if self.seller.resources.get(self.resource, 0) < amount:
                self.status.text = "У продавца недостаточно ресурса"
                return
            cost = amount * price
            if self.buyer.coins < cost:
                self.status.text = "У покупателя недостаточно монет"
                return
            self.seller.resources[self.resource] -= amount
            self.buyer.resources[self.resource] = self.buyer.resources.get(self.resource, 0) + amount
            self.seller.coins += cost
            self.buyer.coins -= cost
            self.app.state.save()
            rname = RESOURCES_BY_CODE[self.resource][1]
            self.status.text = "Обменяно: {}×{} за {}💰".format(amount, rname, cost)
            self._rebuild()
        except Exception:
            log_error()
            self.status.text = "Ошибка сделки"

    def _do_contract(self, *a):
        try:
            p = self._parse_params()
            if not p:
                return
            amount, price = p
            ag = Agreement(Agreement.KIND_TRADE, self.seller.name, self.buyer.name,
                           self.resource, amount, price)
            self.app.state.agreements.append(ag)
            self.app.state.save()
            self.status.text = "Договор заключён: {}×{}/ход".format(
                amount, RESOURCES_BY_CODE[self.resource][1])
        except Exception:
            log_error()
            self.status.text = "Ошибка договора"


