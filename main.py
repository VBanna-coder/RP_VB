def country_workers_demand(country):
    demand = 0
    for n, c in country.extractors.items():
        demand += extractor_workers(n) * c
    for n, c in country.factories.items():
        demand += factory_workers(n) * c
    for n, c in country.advanced.items():
        demand += advanced_workers(n) * c
    return demand


