    def _next_turn(self, *a):
        try:
            state = self.app.state

            for c in state.currencies:
                delta = random.uniform(-0.05, 0.05)
                c.rate *= (1.0 + delta)
                total_pct = 0.0
                new_effects = []
                for eff in c.effects:
                    total_pct += float(eff.get("delta", 0.0))
                    rem = int(eff.get("remaining", 0))
                    if rem > 0:
                        eff["remaining"] = rem - 1
                        if eff["remaining"] > 0:
                            new_effects.append(eff)
                    else:
                        new_effects.append(eff)
                c.effects = new_effects
                c.rate *= (1.0 + total_pct / 100.0)

            for country in state.countries:
                available = country.available_workers()
                new_starved = {}
                new_under = {}
                new_adv_starved = {}
                new_adv_under = {}

                for name, count in list(country.extractors.items()):
                    info = EXTRACTOR_BY_NAME.get(name)
                    if not info:
                        continue
                    w = extractor_workers(name)
                    max_by_workers = min(count, available // w) if w > 0 else count
                    if max_by_workers < count:
                        new_under[name] = count - max_by_workers
                    if max_by_workers > 0:
                        code = info[3]
                        per = info[4]
                        country.resources[code] = (
                            country.resources.get(code, 0) + per * max_by_workers)
                        available -= w * max_by_workers

                for name, count in list(country.factories.items()):
                    info = FACTORY_BY_NAME.get(name)
                    if not info:
                        continue
                    w = factory_workers(name)
                    max_by_workers = min(count, available // w) if w > 0 else count
                    if max_by_workers == 0:
                        new_under[name] = count
                        continue
                    cons = factory_consumption(name)
                    ratios = []
                    for k, v in cons.items():
                        if v <= 0:
                            continue
                        ratios.append(country.resources.get(k, 0) // v)
                    max_by_resources = min(ratios) if ratios else max_by_workers
                    can_run = min(max_by_workers, max_by_resources)
                    if max_by_workers < count:
                        new_under[name] = count - max_by_workers
                    if max_by_resources < max_by_workers:
                        new_starved[name] = max_by_workers - max_by_resources
                    if can_run > 0:
                        for k, v in cons.items():
                            country.resources[k] = (
                                country.resources.get(k, 0) - v * can_run)
                        country.products[name] = (
                            country.products.get(name, 0) + can_run)
                        available -= w * can_run

                for name, count in list(country.advanced.items()):
                    info = ADVANCED_BY_NAME.get(name)
                    if not info:
                        continue
                    w = advanced_workers(name)
                    max_by_workers = min(count, available // w) if w > 0 else count
                    if max_by_workers == 0:
                        new_adv_under[name] = count
                        continue
                    res_cons = advanced_resource_consumption(name)
                    prod_cons = advanced_product_consumption(name)
                    ratios = []
                    for k, v in res_cons.items():
                        if v <= 0:
                            continue
                        ratios.append(country.resources.get(k, 0) // v)
                    for k, v in prod_cons.items():
                        if v <= 0:
                            continue
                        ratios.append(country.products.get(k, 0) // v)
                    max_by_inputs = min(ratios) if ratios else max_by_workers
                    can_run = min(max_by_workers, max_by_inputs)
                    if max_by_workers < count:
                        new_adv_under[name] = count - max_by_workers
                    if max_by_inputs < max_by_workers:
                        new_adv_starved[name] = max_by_workers - max_by_inputs
                    if can_run > 0:
                        for k, v in res_cons.items():
                            country.resources[k] = (
                                country.resources.get(k, 0) - v * can_run)
                        for k, v in prod_cons.items():
                            country.products[k] = (
                                country.products.get(k, 0) - v * can_run)
                            if country.products[k] <= 0:
                                del country.products[k]
                        country.advanced_products[name] = (
                            country.advanced_products.get(name, 0) + can_run)
                        available -= w * can_run

                country.starved = new_starved
                country.understaffed = new_under
                country.advanced_starved = new_adv_starved
                country.advanced_understaffed = new_adv_under
                country.coins += mint_income(country.mints)

                need = population_food_need(country.population)
                for pname in list(country.products.keys()):
                    if need <= 0:
                        break
                    if pname not in FOOD_PRODUCTS:
                        continue
                    take = min(country.products[pname], need)
                    country.products[pname] -= take
                    need -= take
                    if country.products[pname] <= 0:
                        del country.products[pname]
                if need > 0:
                    for code in FOOD_RESOURCES:
                        if need <= 0:
                            break
                        avail = country.resources.get(code, 0)
                        if avail < 10:
                            continue
                        can_feed = min(avail // 10, need)
                        country.resources[code] -= can_feed * 10
                        need -= can_feed
                if need > 0:
                    loss = max(1, int(country.population * 0.01))
                    country.population = max(1000, country.population - loss)
                else:
                    base_rate = 0.001
                    gdp_factor = min(2.0, country.gdp / 50000.0)
                    rate = base_rate * (1 + gdp_factor * 0.5)
                    growth = max(1, int(country.population * rate))
                    country.population += growth
                if country.army > country.population:
                    country.army = country.population

            for ag in list(state.agreements):
                a = state.find_country(ag.a_name)
                b = state.find_country(ag.b_name)
                if not a or not b:
                    state.agreements.remove(ag)
                    continue
                if ag.kind == Agreement.KIND_TRADE:
                    if a.resources.get(ag.resource, 0) < ag.amount:
                        continue
                    cost = ag.amount * ag.price
                    if b.coins < cost:
                        continue
                    a.resources[ag.resource] -= ag.amount
                    b.resources[ag.resource] = (
                        b.resources.get(ag.resource, 0) + ag.amount)
                    a.coins += cost
                    b.coins -= cost
                elif ag.kind == Agreement.KIND_COINS:
                    if a.coins < ag.amount:
                        continue
                    a.coins -= ag.amount
                    b.coins += ag.amount
                elif ag.kind == Agreement.KIND_RESOURCE:
                    if a.resources.get(ag.resource, 0) < ag.amount:
                        continue
                    a.resources[ag.resource] -= ag.amount
                    b.resources[ag.resource] = (
                        b.resources.get(ag.resource, 0) + ag.amount)

            for c in state.currencies:
                if not c.linked_countries:
                    continue
                total = 0.0
                valid = 0
                for cname in c.linked_countries:
                    country = state.find_country(cname)
                    if country:
                        total += country.economy_score()
                        valid += 1
                if valid > 0:
                    avg = total / valid
                    c.rate *= (1.0 + avg / 100.0)

            for c in state.currencies:
                c.rate = max(RATE_MIN, min(RATE_MAX, c.rate))
                c.history.append(c.rate)
                if len(c.history) > HISTORY_LIMIT:
                    c.history = c.history[-HISTORY_LIMIT:]
                c.linked_countries = [
                    n for n in c.linked_countries
                    if state.find_country(n)
                ]

            state.turn += 1
            state.save()
            self.refresh()
        except Exception:
            log_error()


