def make_palette():
    pal = []
    for i in range(100):
        h = (i / 100.0) % 1.0
        r, g, b = colorsys.hsv_to_rgb(h, 0.75, 0.95)
        pal.append((round(r, 3), round(g, 3), round(b, 3), 1.0))
    return pal

